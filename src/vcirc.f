            IF(OMEGA(I)*HRU(I)**2.LT.WMIN*HRU(I-1)**2)THEN
               FX = MAX(2.0D0*DLNJMDR,0.25D0*DLNWDR)
               FX2 = MAX(2.0D0*DLNJMDR0,0.25D0*DLNWDR0)
               VGSF(I) = VGSF(I)*FX/FX2
            ELSE
               VGSF(I)=VGSF(I)*DLNWDR/DLNWDR0
            ENDIF
C            ELSE IF(IGSF.EQ.3)THEN
