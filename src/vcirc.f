      IF(IMU.EQ.3)THEN
         IF(IT.GT.1)THEN
            DO I = 1,M
               VMU(I) = 0.5D0*(VMU(I)+VMUP(I))
            END DO
         ENDIF
         DO I = IMIN,IMAX
