      COMMON/CONSTANTS/CLSUN,CLSUNL,CLNSUN,CMSUN,CMSUNL,CRSUN,CRSUNL,
     *  CMBOL,CLN,CLNI,C4PI,C4PIL,C4PI3L,CC13,CC23,CPI,CGAS,CA3,CA3L,
     *  CSIG,CSIGL,CGL,CMKH,CMKHN,CDELRL,CMIXL2,CMIXL3,CLNDP,CSECYR
C 10/12/26 MHP via Claude
C code changed to extend COMMON/NMLPAR/ to 234 members, adding the
C namelist variables that the physics routines read from 27 COMMON
C blocks which also held derived or working members.  Those blocks keep
C only their non-namelist members; five of them -- NEWMX, VMULT,
C PMMWIND, CCOUT1 and ENVGEN -- had nothing left and are gone.
C Derivation-only namelist variables from the same blocks went to
C COMMON/NMLBYPASS/ instead, not here.
C
C Declared identically in all 121 files that hold any of these members.
C Generated from one member list, so every copy is byte-identical; the
C linker's 'size of symbol changed' warning is the check that they are.
      COMMON/NMLPAR/
     * ALATM_FeH,ALATM_Alpha,LALTPTau100,SLI6,SLI7,SBE91,SBE92,SBE93,
     * CMIN,ABSTOL,RELTOL,KEMMAX,TOLL,TOLR,TOLZ,LCALS,LCALSOLZX,
     * CALSOLZX,CALSOLAGE,LDEBUG,LCORR,LMILNE,LTRACK,LSTPCH,LRWSH,
     * CSTMIXING,CSTDIFFMIX,LCORE,MCORE,FCORE,DTWIND,LPTIME,DTDIF,
     * DJOK,ITDIF1,ITDIF2,LEXCOM,LTRIST,DT_GS,XMIN,YMIN,LTHOULFIT,
     * FGRY,FGRZ,LTHOUL,LDIFZ,LNEWDIF,LDIFLI,GRTOL,ILAMBDA,NITER_GS,
     * LDIFY,LKUTHE,ATMERR,ATMD0,ATMBEG,ATMMIN,ATMMAX,ENVERR,ENVBEG,
     * ENVMIN,ENVMAX,CODM,LCODM,DMDT0,FCZDMDT,FTOTDMDT,COMPACC(15),
     * CREIM,LREIMER,LMDOT,XNEWCP,INEWCP,LNEWCP,LREL,NITER4,LNEWS,
     * LSNU,XENV0A(50),ZENV0A(50),CMIXLA(50),LSENV0A(50),SENV0A(50),
     * LNOJ,lopale06,lNumDeriv,POA,POB,POC,POMAX,LPOUT,WNEW,WALPCZ,
     * ACFPFT,ITFP1,ITFP2,LROT,LINSTB,LWNEW,LSOLID,IMPJMOD,SPOTF,
     * SPOTX,LSDEPTH,ITRVER,FESC,FSSC,FGSFC,IES,IGSF,IMU,VNEW(12),
     * WEAKSCREENING,KTTAU,KTTAU0,LTTAU,XLS,XLSTOL,STEFF,SR,LTEFF,
     * LCALST,LSTORE,LSTATM,LSTENV,LSTMOD,LSTPHYS,LSTROT,LSTCH,
     * NPRTMOD,NPRTPT,NPOINT,TRIDT,TRIDL,LNEW0,NMODLS(50),LFIRST(50),
     * NUMRUN,SSTANDARD(17),ATIME(14),TCUT(5),TSCUT,TENV0,TENV1,TGCUT,
     * HTOLER(5,2),FCORR0,FCORRI,HPTTOL(12),NITER1,NITER2,NITER3,WMAX,
     * EXMD,EXW,EXTAU,EXR,EXM,EXL,EXPR,CONSTFACTOR,EXCEN,LJDOT0,
     * ETADH0,ETADH1,LDH,TDISK,PDISK,LDISK,DPENV,ALPHAC,ALPHAE,ALPHAM,
     * BETAC,LOVSTC,LOVSTE,LOVSTM,LSEMIC,LADOV,LOVMAX,ATMSTP,ENVSTP,
     * LSOLWIND,LMIXTURE,LISOTOPE,FRAC_C,FRAC_N,FRAC_O,R12_13,R16_18,
     * XH2_INI,XHE3_INI,XLI6_INI,XLI7_INI,XBE9_INI,ZOPAL951,TMOLMIN,
     * TMOLMAX,TOLLAOL,LALEX06,LOPAL95,LPUREZ,LcondOpacP,LNULOS1,
     * OPTOL,LNEWTCZ,LCALCENV,PMMSOLP,PMMSOLW,PMMSOLTAU,LMWIND,
     * LROSSBY,LBSCALE,LPULSE,IPVER,LSCV,ENDAGE(50),SETDT(50),
     * END_DCEN(50),END_XCEN(50),END_YCEN(50),LVFC,LDIFAD,FW,FC,FES,
     * FGSF,FMU,FSS,RCRIT,RSCLZC(50),RSCLZM1(50),RSCLZM2(50),LZRAMP
      COMMON/OPTAB/ZSI,IDT,IDD(4)
      COMMON/SCRTCH/SESUM(JSON),SEG(7,JSON),SBETA(JSON),SETA(JSON),
     * LOCONS(JSON),SO(JSON),SDEL(3,JSON),SFXION(3,JSON),SVEL(JSON),SCP(JSON)
      COMMON/TEMP/CP(JSON),HAMU(JSON),SQDT(JSON),THDIF(JSON),
     *     VISC(JSON)
      COMMON/DWMAX/QWRMAX(JSON),QWRMX0(JSON)
C DBG 7/92 COMMON BLOCK ADDED TO COMPUTE DEBYE-HUCKEL CORRECTION.
      COMMON/DEBHU/CDH,ZDH(18),XXDH,YYDH,ZZDH,DHNUE(18)
      COMMON/DPMIX/IOV1,IOV2,IOVIM
      DIMENSION HCOMP(15,JSON),HD(JSON),HL(JSON),HG(JSON),
     *     HP(JSON),HR(JSON),HS(JSON),HT(JSON),LC(JSON),
C      *     FXION(3),FP(JSON),FT(JSON),ATOMWT(4),LCZ(JSON),  ! KC 2025-05-31
     *     FXION(3),FP(JSON),FT(JSON),ATOMWT(4),
     *     HF(4),HOLD(4)
      DATA ATOMWT/1.007825D0,4.002603D0,12.0D0,3.01603D0/
      SAVE

C  FIND ACTUAL AND ADIABATIC TEMPERATURE GRADIENTS,OPACITY,AND
C  MEAN MOLECULAR WEIGHT FOR ALL RADIATIVE SHELLS.
      LDERIV = .FALSE.
      LOCOND = .FALSE.
      LATMO = .FALSE.
      IDT = 15
      DO 25 I = 1,4
         IDD(I) = 5
 25   CONTINUE
      DO 30 IM = 1,M
         SL = HS(IM)
         TL = HT(IM)
         PL = HP(IM)
         RL = HR(IM)
         B = HL(IM)
         X = HCOMP(1,IM)
         Z = HCOMP(3,IM)
         DL = HD(IM)
         FPL = FP(IM)
         FTL = FT(IM)

C 9/22/26 MHP via Claude
C code changed to remove the MHD equation of state
         IF (LDH) THEN
            XXDH = HCOMP(1,IM)
            YYDH = HCOMP(2,IM)+HCOMP(4,IM)
            ZZDH = HCOMP(3,IM)
            ZDH(1) = HCOMP(5,IM)+HCOMP(6,IM)
            ZDH(2) = HCOMP(7,IM)+HCOMP(8,IM)
            ZDH(3) = HCOMP(9,IM)+HCOMP(10,IM)+HCOMP(11,IM)
         END IF
         CALL EQSTAT(TL,T,PL,P,DL,D,X,Z,BETA,BETAI,BETA14,FXION,RMU,
     *        AMU,EMU,ETA,QDT,QDP,QCP,DELA,QDTT,QDTP,QAT,QAP,QCPT,
     *        QCPP,LDERIV,LATMO,KSAHA)
         CALL GETOPAC (DL,TL,X,Z,O,OL,QOD,QOT,FXION)
         IOVIM=IM
         CALL TPGRAD(TL,T,PL,P,D,RL,SL,B,O,QDT,QDP,QOT,QOD,QCP,DEL,
     *        DELR,DELA,QDTT,QDTP,QAT,QAP,QACT,QACP,QACR,QCPT,QCPP,
     *        VEL,LDERIV,LCONV,FPL,FTL,TEFFL,CMIXL)
         LC(IM) = LCONV
         SDEL(1,IM) = DELR
         SDEL(2,IM) = DEL
         SDEL(3,IM) = DELA
C  FIND NEW RUN OF MEAN MOLECULAR WEIGHT ASSUMING FULLY IONIZED GAS.
C  AMUENV IS(1/MEAN MOLECULAR WEIGHT PER ION OF THE SURFACE MIXTURE.)
         DFX1 = HCOMP(1,IM) - XENV
         DFX2 = HCOMP(2,IM) - YENV
         DFX3 = HCOMP(3,IM) - ZENV
         DFX4 = HCOMP(4,IM) - Y3ENV
         TEMP = AMUENV + DFX1/ATOMWT(1) + DFX2/ATOMWT(2) +
     *        DFX3/ATOMWT(3) + DFX4/ATOMWT(4)
         AMU2 = 1.0D0/TEMP
         TEMP = HCOMP(1,IM)/ATOMWT(1) + 2.0D0*(HCOMP(4,IM)/ATOMWT(4)
     *        + HCOMP(2,IM)/ATOMWT(2)) + 0.5D0*HCOMP(3,IM)
         EMU2 = 1.0D0/TEMP
         HAMU(IM) = AMU2*EMU2/(AMU2+EMU2)
         SO(IM) = O
         CP(IM) = QCP
         SQDT(IM) = QDT
C JVS 10/13 Always want SVEL
         SVEL(IM) = VEL
C         IF(LC(IM))THEN
C            SVEL(IM) = VEL
C         ELSE
C            SVEL(IM) = 0.0D0
C         ENDIF
 30   CONTINUE
C  FIND THE THERMOMETRIC DIFFUSIVITY AND KINEMATIC VISCOSITY.
C       CALL VISCOS(HCOMP,HD,HT,LC,M)  ! KC 2025-05-31
      CALL VISCOS(HCOMP,HD,HT,M)
C  FIND THE RUN OF MAXIMUM ALLOWABLE D OMEGA/D LNR AND THE RUN OF ACTUAL
C  D OMEGA/D LN R FOR ALL RADIATIVE ZONES.
C  IF THE GRADIENT OF OMEGA EXCEEDS THE CRITICAL VALUE FOR THE SHEAR
C  INSTABILITY, A SHORT TIMESCALE INSTABILITY OCCURS.  MIX ALL ADJACENT
C  UNSTABLE ZONES TO A MARGINALLY STABLE STATE.
      DO 100 IM = 2,M
C  SKIP CONVECTIVE REGIONS
         IF(LC(IM).AND.LC(IM-1))THEN
            QWRMAX(IM) = 0.0D0
            GOTO 100
         ENDIF
C  NOW CHECK FOR SHEAR INSTABILITY -REF.ENDAL&SOFIA APJ 220:279(1978)
C  THERMODYNAMIC QUANTITIES ARE CALCULATED AT THE SHELL MIDPOINT BY
C  4-POINT LAGRANGIAN INTERPOLATION.
         IF(IM.LE.2) THEN
            K = 1
         ELSE IF(IM.EQ.M) THEN
            K = M - 3
         ELSE
            K = IM - 2
         ENDIF
         DO 90 I = 1, 4
            HOLD(I) = HS(I+K-1)
 90      CONTINUE
C  USE 4-POINT LAGRANGIAN INTERPOLATION TO FIND PHYSICAL VARIABLES
C  AT THE INTERFACE BEING TESTED.
         HSMID = 0.5D0*(HS(IM) + HS(IM-1))
         CALL INTRP2(HOLD,HF,HSMID)
         PMID=HP(K)*HF(1) + HP(K+1)*HF(2) + HP(K+2)*HF(3) +HP(K+3)*HF(4)
         DMID=HD(K)*HF(1) + HD(K+1)*HF(2) + HD(K+2)*HF(3) +HD(K+3)*HF(4)
         DELMID=SDEL(2,K)*HF(1) + SDEL(2,K+1)*HF(2) + SDEL(2,K+2)*HF(3)
     *        + SDEL(2,K+3)*HF(4)
         DELAMD=SDEL(3,K)*HF(1) + SDEL(3,K+1)*HF(2) + SDEL(3,K+2)*HF(3)
     *        + SDEL(3,K+3)*HF(4)
         GMID=HG(K)*HF(1) + HG(K+1)*HF(2) + HG(K+2)*HF(3) +HG(K+3)*HF(4)
         TEMP = DEXP(CLN*(DMID - PMID))*(DELAMD - DELMID)*GMID**2
         IF(TEMP.GT.0.0D0) THEN
            QWRMAX(IM) = 2.0D0*DSQRT(TEMP)
         ELSE
            QWRMAX(IM) = 0.0D0
         ENDIF
 100  CONTINUE

      RETURN
      END
